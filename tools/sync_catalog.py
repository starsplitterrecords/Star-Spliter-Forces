#!/usr/bin/env python3
"""Builds data/catalog.json from the Star Splitter Records artist JSON.

Every release listed on the Records site that is not already in the game
becomes a catalogue track (verbatim title and meta, with its source file).
The game turns each one into a findable record signal. Also rewrites the
generated block in MUSIC_CATALOG_MANIFEST.md, which the tests check titles
against.

Usage:
  python3 tools/sync_catalog.py <path to StarSplitterVisions clone>

Projects whose use needs owner consent are skipped (BLOCKED). Titles that are
data errors in the source are skipped (BAD_TITLES).
"""
import json
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(ROOT, "data", "catalog.json")
MANIFEST = os.path.join(ROOT, "MUSIC_CATALOG_MANIFEST.md")
GAME_DATA = os.path.join(ROOT, "scripts", "data", "game_data.gd")
BLOCKED = {"jeff-hines"}  # a real person's name; needs owner consent (DECISIONS D-49)
BAD_TITLES = {"feat. Cheddr"}  # Warm Circuits Rise data error in the source JSON
BEGIN = "<!-- BEGIN GENERATED CATALOG (tools/sync_catalog.py) -->"
END = "<!-- END GENERATED CATALOG -->"


def slug(text):
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    ssv = sys.argv[1]
    art_dir = os.path.join(ssv, "sites", "records", "content", "artists")
    game = open(GAME_DATA, encoding="utf-8").read()
    existing_titles = set(re.findall(r'"title": "([^"]+)", "meta"', game))
    projects = {}
    tracks = []
    for fn in sorted(os.listdir(art_dir)):
        if not fn.endswith(".json"):
            continue
        a = json.load(open(os.path.join(art_dir, fn), encoding="utf-8"))
        if a.get("slug") in BLOCKED:
            continue
        name = a["name"]
        rels = [r for r in a.get("releases", []) if r.get("title") and r["title"] not in BAD_TITLES]
        new = [r for r in rels if r["title"] not in existing_titles]
        if not new:
            continue
        projects[name] = {"field": a.get("field", ""), "role": a.get("catalogRole", ""), "accent": a.get("accent", "#cfe9ff"),
                          "bio": a.get("oneSentenceBio", ""), "source": "sites/records/content/artists/" + fn}
        for r in new:
            meta = r.get("meta") or r.get("status") or ""
            tracks.append({"id": slug(name)[:10] + "_" + slug(r["title"])[:28], "project": name, "title": r["title"], "meta": meta,
                           "source": "sites/records/content/artists/" + fn})
    data = {"about": "Generated by tools/sync_catalog.py from Star Splitter Records artist JSON. Titles and metas are verbatim. Do not hand-edit titles; add masters under audio/catalog/<id>.ogg.",
            "projects": projects, "tracks": tracks}
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    json.dump(data, open(OUT, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    rows = ["| %s | %s — %s · %s | `%s` |" % (t["id"], t["project"], t["title"], t["meta"], t["source"]) for t in tracks]
    block = "\n".join([BEGIN, "", "### Catalogue records (generated)", "",
                       "Each becomes a record signal hidden somewhere on a later expedition.", "",
                       "| Track id | Project — Title · meta (verbatim) | Source |", "|---|---|---|"] + rows + ["", END])
    man = open(MANIFEST, encoding="utf-8").read()
    if BEGIN in man:
        man = man[:man.index(BEGIN)] + block + man[man.index(END) + len(END):]
    else:
        man = man.rstrip() + "\n\n" + block + "\n"
    open(MANIFEST, "w", encoding="utf-8").write(man)
    print("catalog: %d projects, %d tracks -> %s" % (len(projects), len(tracks), OUT))


if __name__ == "__main__":
    main()
